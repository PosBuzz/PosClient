import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const manifest = {
  consumer: [
    ["sale-detail", "sale", "Sale"],
    ["quotation-detail", "sale", "Sale"],
    ["sales-list", "sale", "SaleListResponse"],
    ["return-detail", "return", "Return"],
    ["returns-list", "return", "ReturnListResponse"],
    ["sale-by-number", "return", "SaleForReturn"],
    ["partial-payments", "payment", "PartialPaymentListResponse"],
    ["product-detail", "product", "Product"],
    ["products-for-sale", "sale", "ProductVariantForSale[]"],
    ["products-list", "product", "ProductListResponse"],
    ["customer-summary", "customer", "CustomerSummary"],
    ["customer-points", "rewards", "CustomerRewardsPoints"],
    ["rewards-settings", "rewards", "RewardsSettings"],
    ["promotions-active", "promotion", "Promotion[]"],
    ["promotions-list", "promotion", "Promotion[]"],
    ["promotion-options", "promotion", "PromotionOptionsResponse"],
    ["eod", "sale", "EODReportResponse"],
    ["dashboard", "sale", "DashboardAnalyticsResponse"],
    ["daily-target", "sale", "DailyTargetReportResponse"],
    ["auth-client", "auth", "AuthResponse"],
  ],
  admin: [["auth-admin", "auth", "AuthResponse"]],
};

/** JSON imports widen string literals and infer null as any. Preserve exact fixture
 * values for enum/null checking, and map nominal TS enums to their JSON string values.
 * Readonly affects only these generated test literals, never production models. */
const prelude = `// Generated by scripts/contracts/generate-response-types.mjs. Do not edit.
// Regenerate after reviewing backend response changes; --check rejects stale copies.
type JsonShape<T> = T extends string ? \`\${T}\` : T extends readonly (infer V)[] ? readonly JsonShape<V>[] : T extends object ? { readonly [K in keyof T]: JsonShape<T[K]> } : T;
type ImportShape<T> = T extends string ? string : T extends number ? number : T extends boolean ? boolean : T extends readonly (infer V)[] ? readonly ImportShape<V>[] : T extends object ? { readonly [K in keyof T]: ImportShape<T[K]> } : T;
import type { useAuthStore } from "../stores/authStore";
type AuthResponse = { user: NonNullable<ReturnType<typeof useAuthStore.getState>["user"]> };
`;

let stale = false;
for (const [app, cases] of Object.entries(manifest)) {
  if (
    process.argv.includes("--app") &&
    process.argv[process.argv.indexOf("--app") + 1] !== app
  )
    continue;
  const lines = [prelude];
  for (const [name, module, target] of cases) {
    const id = name.replace(/-/g, "_");
    const alias = `${id}_Type`;
    if (module !== "auth")
      lines.push(
        `import type { ${target.replace("[]", "")} as ${alias} } from "../types/${module}.types";`,
      );
    const type =
      module === "auth"
        ? "AuthResponse"
        : `${alias}${target.endsWith("[]") ? "[]" : ""}`;
    const body = JSON.parse(
      readFileSync(
        resolve(root, "contracts/responses", `${name}.json`),
        "utf8",
      ),
    );
    lines.push(
      `import source_${id} from "../../../contracts/responses/${name}.json";`,
    );
    lines.push(`const literal_${id} = ${JSON.stringify(body)} as const;`);
    lines.push(
      `export const contract_${id}: JsonShape<${type}> = literal_${id};`,
    );
    // Direct tsc still sees field/type changes in the imported JSON. --check additionally
    // catches changed literal values and nulls that TypeScript's JSON importer widens.
    lines.push(
      `export const source_${id}_shape: ImportShape<typeof literal_${id}> = source_${id};`,
    );
  }
  const text = `${lines.join("\n")}\n`;
  const file = resolve(root, app, "src/test/contract-types.ts");
  if (process.argv.includes("--check")) {
    let current;
    try {
      current = readFileSync(file, "utf8");
    } catch {
      current = "";
    }
    if (current !== text) {
      console.error(
        `${app}: response type fixtures are stale; run node scripts/contracts/generate-response-types.mjs`,
      );
      stale = true;
    }
  } else writeFileSync(file, text);
}
if (stale) process.exitCode = 1;
